YFIX = [("逆上がり", "さかあがり"), ("がお", "ガオ"), ("うんち", "ウンチ"), ("拭いて", "ふいて"), ("おかわり", "お代わり"), ("明日", "あした"), ("人気", "にんき"),
        ("何時", "なんじ"), ("開けて", "あけて"), ("開けられ", "あけられ"), ("十数え", "じゅう数え")]
def yfix(t):
    for a, b in YFIX: t = t.replace(a, b)
    return t
def fix_all(s):
    for f in ("qy", "ry"):
        if f in s: s[f] = yfix(s[f])
    for t in s["tiers"]:
        if "y" in t: t["y"] = yfix(t["y"])
        if "wy" in t: t["wy"] = yfix(t["wy"])
    return s

