G2FIX = [("面白れー", "おもしれー"), ("一口", "ひとくち"), ("上手", "じょうず"), ("変な音", "へんなおと"), ("音を", "おとを"), ("音に", "おとに"), ("合奏", "がっそう"), ("並べて", "ならべて"), ("下手くそ", "ヘタクソ"), ("ぴょんさんとみいさん", "ぴょんさんと、みいさん"), ("ぴょんさんとどしんくん", "ぴょんさんと、どしんくん"), ("にんじん嫌い", "にんじん、きらい"), ("て「", "て、"), ("「", ""), ("」", "")]
def yf(t):
    for a, b in G2FIX: t = t.replace(a, b)
    return yfix(t)
def fix(s):
    s["qy"] = yf(s["qy"]); s["ry"] = yf(s["ry"])
    for t in s["tiers"]:
        t["y"] = yf(t["y"])
        if "wy" in t: t["wy"] = yf(t["wy"])
    for row in s["talk"] + s["after"]: row[2] = yf(row[2]) if row[2] else row[2]
    return s

