def build():
    kaiwa = KAIWA
    for k in kaiwa: assert len(k["opts"]) == 4 and all(w in k["cast"] for w, _, _ in k["talk"]), k["id"]
    hantai = [{"id": f"h{i}", "w": w, "e": e, "a": a, "ae": ae, "ng": [list(x) for x in ng]} for i, (w, e, a, ae, ng) in enumerate(HANTAI)]
    joshi = [{"id": f"j{i}", "e": e, "words": ws, "y": y} for i, (e, ws, y) in enumerate(JOSHI)]
    machi = []
    for i, (s, errs, y) in enumerate(MACHI):
        fixed = s; items = []
        for mark, ok, alt in errs:
            ch = mark[0]; nth = int(mark[1:]) if len(mark) > 1 else 1
            pos = -1
            for _ in range(nth): pos = s.index(ch, pos + 1)
            items.append({"pos": pos, "bad": ch, "ok": ok, "alt": alt})
        chars = list(s)
        for it in items: chars[it["pos"]] = it["ok"]
        machi.append({"id": f"m{i}", "s": s, "fix": "".join(chars), "errs": items, "y": y})
    teinei = [{"id": f"t{i}", "kind": k, "q": q, "e": e, "ok": ok, "ng": ng, "oke": WHO_EMOJI.get(ok, ""), "nge": WHO_EMOJI.get(ng, "")} for i, (k, q, e, ok, ng) in enumerate(TEINEI)]
    return {"kaiwa": kaiwa, "hantai": hantai, "joshi": joshi, "machi": machi, "teinei": teinei}

