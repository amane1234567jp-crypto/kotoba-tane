import json
kana = {l.split("\t")[1]: l.split("\t")[2] for l in open("sit/kana.txt") if l.count("\t") >= 2}
rep = [("コロンデ'", "コロ'ンデ"), ("キノオ'", "キノ'オ"), ("_シツ'レエ/シマ'_ス", "_シツレエ_シマ'_ス"), ("ガオニ'", "ガ'オニ"),
       ("オサレタ'", "オ'サレタ"), ("オサレテ'", "オ'サレテ"), ("アラウ'/ノオ'", "アラウノオ'"), ("ノッテ'、イル'", "ノ'ッテイル"), ("イエニ'", "イ'エニ")]
whole = {"あら、どうしたの？": "アラ'、ド'オ_シタノ？", "おや、どうしたのかね？": "オ'ヤ、ド'オ_シタノカネ？",
  "なにか、さがして いるのですか？": "ナ'ニカ、サガ'_シテ、イル'ノデ_スカ？",
  "ずかんなら、いちばん うえの たなに ありますよ": "ズカンナラ'、イチ'バン、ウ'エノ、タナニ'、アリマ'_スヨ",
  "そうそう。せっけんで、あわあわに してね": "ソ'オソオ、セッケンデ'、アワアワニ'、_シテネ'",
  "お、おもいよう……": "オ'、オモ'イヨオ", "あ、ありがとう！ たすかったよう": "ア'、アリ'ガトオ、タ_スカ'ッタヨオ",
  "おや、だれかな？ はいって いいですよ": "オ'ヤ、ダ'レカナ？、ハ'イッテ、イ'イデ_スヨ",
  "ほっほ。ありがとう。りっぱな あいさつですね": "ホ'ッホ、アリ'ガトオ、リッパナ'、ア'イサツデ_スネ",
  "ほっほ。よい あいさつだ。いってらっしゃい": "ホ'ッホ、ヨ'イ、ア'イサツダ、イッテラッシャイ'",
  "まあ。がおくんには、あとで おはなし しておくわね": "マ'ア、ガ'オクンニワ、ア'トデ、オハナシ'、_シテオク'ワネ"}
fix = dict(whole)
for text, k in kana.items():
    if text in fix: continue
    n = k
    for a, b in rep: n = n.replace(a, b)
    if n != k: fix[text] = n
json.dump(fix, open("sit/fix.json", "w"), ensure_ascii=False, indent=0)
print(len(fix))
